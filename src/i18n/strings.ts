export const STRINGS: Record<Lang, Record<string, string>> = { it, en };

/** Testo localizzato con interpolazione `{nome}`. Chiave mancante → restituisce la chiave. */
export function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const table = STRINGS[lang] ?? STRINGS.en;
  const raw = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : undefined;
  if (raw === undefined) return key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m,
  );
}
